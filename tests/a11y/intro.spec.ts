import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { boot } from './support'

test.describe('first experience', () => {
  test('welcomes a first visit in Polish, then stays dismissed', async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 800 })
    await boot(page, { locale: 'pl', mode: 'technical', intro: 'fresh' })
    const dialog = page.locator('[data-intro-dialog]')
    await expect(dialog.getByRole('heading', { name: 'FIELD' })).toBeVisible()
    await expect(dialog.getByText('Przestrzeń do odkrywania dźwięku.')).toBeVisible()
    const welcomeAxe = await new AxeBuilder({ page })
      .include('[data-intro-dialog]')
      .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'])
      .analyze()
    expect(welcomeAxe.violations).toEqual([])
    await page.screenshot({ path: '/opt/cursor/artifacts/welcome-pl.png' })
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: 'Odkryj FIELD' })).toBeFocused()
    await dialog.getByRole('button', { name: 'Rozpocznij pracę' }).click()
    await expect(dialog).toHaveCount(0)
    await page.reload()
    await expect(page.getByRole('button', { name: 'Ustawienia', exact: true })).toBeVisible()
    await expect(page.locator('[data-intro-dialog]')).toHaveCount(0)
    const stored = await page.evaluate(() => localStorage.getItem('field.intro'))
    expect(stored).toContain('"seen":true')
    expect(stored).not.toContain('@')
  })

  test('walks the guide and returns to it from help', async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 800 })
    await boot(page, { locale: 'pl', mode: 'simple', intro: 'fresh' })
    const dialog = page.locator('[data-intro-dialog]')
    await dialog.getByRole('button', { name: 'Odkryj FIELD' }).click()
    await expect(dialog.getByRole('heading', { name: 'Twój dźwięk' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Dalej' }).click()
    await expect(dialog.getByRole('heading', { name: 'Wybierz sposób pracy' })).toBeVisible()
    await page.screenshot({ path: '/opt/cursor/artifacts/tour-modes-pl.png' })
    await expect(dialog.getByText('Prosty', { exact: false }).first()).toBeVisible()
    await dialog.getByRole('button', { name: 'Wstecz' }).click()
    await expect(dialog.getByRole('heading', { name: 'Twój dźwięk' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)

    await page.getByRole('button', { name: 'Pomoc', exact: true }).first().click()
    await expect(dialog.getByRole('heading', { name: 'Pomoc' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Uruchom przewodnik' }).click()
    await expect(dialog.getByRole('heading', { name: 'Twój dźwięk' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Pomiń' }).click()
    await expect(dialog).toHaveCount(0)
  })

  test('keeps optional feedback answers when sending is not configured', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await boot(page, { locale: 'pl', mode: 'technical', theme: 'black-white', intro: 'fresh', reducedMotion: 'reduce' })
    await page.locator('[data-intro-dialog]').getByRole('button', { name: 'Rozpocznij pracę' }).click()
    await page.getByRole('button', { name: 'Ustawienia', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Prześlij opinię' }).click()
    const dialog = page.locator('[data-intro-dialog]')
    await expect(dialog.getByRole('heading', { name: 'Pomóż rozwijać FIELD' })).toBeVisible()
    await expect(dialog.getByText('Co działa dobrze, a co można poprawić?')).toHaveCount(0)
    await dialog.getByRole('group', { name: 'Czy korzystasz z funkcji dostępności?' }).getByRole('radio', { name: 'Tak', exact: true }).click()
    await expect(dialog.getByText('Co działa dobrze, a co można poprawić?')).toBeVisible()
    await dialog.getByRole('button', { name: 'Wyślij opinię' }).click()
    await expect(dialog.getByRole('alert')).toBeVisible()
    const note = dialog.getByLabel('Co sprawiło Ci największą trudność?')
    await note.fill('Na telefonie trudno znaleźć eksport.')
    await dialog.getByLabel('Adres e-mail').fill('not-an-email')
    await dialog.getByRole('button', { name: 'Wyślij opinię' }).click()
    await expect(dialog.getByRole('alert')).toContainText('e-mail')
    await expect(note).toHaveValue('Na telefonie trudno znaleźć eksport.')
    await dialog.getByLabel('Adres e-mail').fill('')
    await dialog.getByRole('button', { name: 'Wyślij opinię' }).click()
    await expect(dialog.getByRole('alert')).toContainText('nie jest jeszcze włączona')
    await dialog.getByRole('alert').scrollIntoViewIfNeeded()
    await page.screenshot({ path: '/opt/cursor/artifacts/feedback-phone-pl.png' })
    await expect(note).toHaveValue('Na telefonie trudno znaleźć eksport.')
    await expect(dialog.getByRole('heading', { name: 'Dziękujemy!' })).toHaveCount(0)
    const geometry = await page.evaluate(() => ({
      scroll: document.documentElement.scrollWidth,
      width: window.innerWidth,
    }))
    expect(geometry.scroll).toBeLessThanOrEqual(geometry.width + 1)
    const axe = await new AxeBuilder({ page })
      .include('[data-intro-dialog]')
      .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa'])
      .analyze()
    expect(axe.violations).toEqual([])
  })

  test('shows the English guide from the header', async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await boot(page, { locale: 'en', mode: 'technical' })
    await page.locator('[data-intro-help]').click()
    const dialog = page.locator('[data-intro-dialog]')
    await expect(dialog.getByRole('heading', { name: 'Help' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Start the guide' }).click()
    await expect(dialog.getByRole('heading', { name: 'Your sound' })).toBeVisible()
    await page.screenshot({ path: '/opt/cursor/artifacts/guide-en.png' })
    await page.keyboard.press('Escape')
    await expect(page.locator('[data-intro-help]')).toBeFocused()
  })
})
