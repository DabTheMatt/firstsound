import { expect, test } from '@playwright/test'
import { boot, loadDemo, openAccess } from './support'

test.describe('keyboard and focus', () => {
  test('tabs between controls and reverses with Shift+Tab', async ({ page }) => {
    await boot(page)
    await page.keyboard.press('Tab')
    const first = await page.evaluate(() => document.activeElement?.getAttribute('aria-label') || document.activeElement?.textContent)
    await page.keyboard.press('Tab')
    const second = await page.evaluate(() => document.activeElement?.getAttribute('aria-label') || document.activeElement?.textContent)
    expect(second).not.toBe(first)
    await page.keyboard.press('Shift+Tab')
    const back = await page.evaluate(() => document.activeElement?.getAttribute('aria-label') || document.activeElement?.textContent)
    expect(back).toBe(first)
  })

  test('Enter opens Settings and Escape restores the trigger', async ({ page }) => {
    await boot(page)
    const settings = page.getByRole('button', { name: 'Settings', exact: true })
    await settings.focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Settings' })
    await expect(dialog).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Settings' })).toBeFocused()
    const outline = await page.evaluate(() => getComputedStyle(document.activeElement as HTMLElement).outlineStyle)
    expect(outline).not.toBe('none')
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    await expect(settings).toBeFocused()
  })

  test('Space activates a switch and does not start playback', async ({ page }) => {
    await boot(page)
    await openAccess(page)
    const motion = page.getByRole('switch', { name: 'Reduced Motion' })
    await motion.focus()
    await page.keyboard.press('Space')
    await expect(motion).toBeChecked()
    await expect(page.getByRole('button', { name: 'Play', exact: true }).first()).toBeVisible()
    await expect(page.locator('html')).toHaveAttribute('data-reduce-motion', 'on')
  })

  test('Space types into Export and does not toggle transport', async ({ page }) => {
    await boot(page)
    await loadDemo(page)
    await page.getByRole('button', { name: 'Export', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Export' })
    await expect(dialog).toBeVisible()
    const name = dialog.getByRole('textbox')
    await expect(name).toBeFocused()
    await name.fill('')
    await page.keyboard.type('field take')
    await page.keyboard.press('Space')
    await expect(name).toHaveValue('field take ')
    await expect(page.getByRole('button', { name: 'Pause', exact: true })).toHaveCount(0)
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    await expect(page.locator('[data-export-open]')).toBeFocused()
  })

  test('keeps focus on the mode that was chosen', async ({ page }) => {
    await boot(page)
    await page.getByRole('radio', { name: 'Simple' }).click()
    await expect(page.getByRole('radio', { name: 'Simple' })).toBeFocused()
    await page.getByRole('radio', { name: 'Sensory' }).click()
    await expect(page.getByRole('radio', { name: 'Sensory' })).toBeFocused()
    await page.getByRole('radio', { name: 'Technical' }).click()
    await expect(page.getByRole('radio', { name: 'Technical' })).toBeFocused()
  })

  test('moves focus into Focus Mode and back out', async ({ page }) => {
    await boot(page)
    await page.getByRole('button', { name: 'Enter Focus Mode' }).click()
    const exit = page.getByRole('button', { name: 'Exit Focus Mode' })
    await expect(exit).toBeFocused()
    await page.keyboard.press('Tab')
    const inside = await page.evaluate(() => document.activeElement?.getAttribute('aria-label') || document.activeElement?.textContent)
    expect(inside).toBeTruthy()
    await exit.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Enter Focus Mode' })).toBeFocused()
  })

  test('Guided Tasks can be paused, resumed, and exited without a keyboard trap', async ({ page }) => {
    await boot(page)
    const guide = page.getByRole('button', { name: 'Guide me' }).first()
    await guide.click()
    const panel = page.getByRole('region', { name: 'Guided Tasks' })
    await expect(panel).toBeVisible()
    await page.getByRole('button', { name: /Understand the waveform/ }).click()
    await page.getByRole('region', { name: 'Guided Tasks' }).getByRole('button', { name: 'Generate demo sample' }).click()
    await expect(page.getByRole('heading', { name: 'Time runs left to right' })).toBeVisible({ timeout: 60_000 })
    await page.getByRole('button', { name: 'Learn more' }).click()
    await page.getByRole('button', { name: 'Show me where' }).click()
    await page.keyboard.press('Escape')
    const restore = page.getByRole('button', { name: /Restore guidance/ })
    await expect(restore).toBeVisible()
    await restore.focus()
    await page.keyboard.press('Tab')
    const leftPanel = await page.evaluate(() => !document.activeElement?.closest('[data-guide-restore]'))
    expect(leftPanel).toBe(true)
    await restore.click()
    await page.getByRole('button', { name: 'Next', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Height is amplitude' })).toBeVisible()
    const stillInGuide = await page.evaluate(() => Boolean(document.activeElement?.closest('[role="region"]')))
    expect(stillInGuide).toBe(true)
    await page.getByRole('button', { name: 'Exit', exact: true }).click()
    await expect(panel).toBeHidden()
    await expect(guide).toBeFocused()
  })

  test('names knobs and the waveform region', async ({ page }) => {
    await boot(page)
    await loadDemo(page)
    const slider = page.getByRole('slider').first()
    await expect(slider).toHaveAttribute('aria-valuenow', /.*/)
    const name = await slider.evaluate((el) => el.getAttribute('aria-label') || el.getAttribute('aria-labelledby'))
    expect(name).toBeTruthy()
    const region = page.getByRole('region', { name: 'Waveform editor', exact: true })
    await region.focus()
    const described = await region.evaluate((el) => {
      const id = el.getAttribute('aria-describedby')
      return id ? document.getElementById(id)?.textContent : ''
    })
    expect(described).toMatch(/Duration/)
    expect(described).toMatch(/Playhead/)
    expect(described).toMatch(/Selection/)
  })
})
