import { expect, test } from '@playwright/test'
import { boot, openAccess } from './support'

test.describe('keyboard-only editing', () => {
  test('loads, plays, trims, fades, sets gain, and opens export without a click', async ({ page }) => {
    await boot(page, { mode: 'simple' })
    const settings = page.getByRole('button', { name: 'Settings', exact: true })
    await settings.focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Settings' })
    await dialog.getByRole('button', { name: 'Generate demo sample' }).focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('region', { name: /^Waveform,/ })).toBeVisible({ timeout: 60_000 })
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()

    const play = page.getByRole('button', { name: 'Play', exact: true }).first()
    await play.focus()
    await page.keyboard.press('Enter')
    const pause = page.getByRole('button', { name: 'Pause', exact: true }).first()
    await expect(pause).toBeVisible()
    await pause.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Play', exact: true }).first()).toBeVisible()

    const start = page.getByRole('slider', { name: /Sample start/ })
    await start.focus()
    await page.keyboard.press('ArrowRight')
    await page.keyboard.press('ArrowRight')
    const end = page.getByRole('slider', { name: /Sample end/ })
    await end.focus()
    await page.keyboard.press('ArrowLeft')
    await page.keyboard.press('ArrowLeft')

    const trim = page.getByRole('button', { name: 'Trim to selection', exact: true }).first()
    await expect(trim).toBeEnabled()
    await trim.focus()
    await page.keyboard.press('Enter')

    const fade = page.getByRole('radio', { name: 'Fade in: Short' })
    await fade.focus()
    await page.keyboard.press('Enter')
    await expect(fade).toBeChecked()

    await page.getByRole('tab', { name: 'Edit', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    const sound = page.getByRole('tab', { name: 'Sound', exact: true })
    await expect(sound).toHaveAttribute('aria-selected', 'true')
    const gain = page.getByRole('slider', { name: /Gain / })
    await gain.focus()
    const before = await gain.inputValue()
    await page.keyboard.press('ArrowRight')
    await expect(gain).not.toHaveValue(before)

    const exportButton = page.locator('[data-simple-export]').first()
    await exportButton.focus()
    await page.keyboard.press('Enter')
    const exporter = page.getByRole('dialog', { name: 'Export' })
    await expect(exporter).toBeVisible()
    const name = exporter.locator('input').first()
    await name.focus()
    await name.fill('')
    await page.keyboard.type('field take')
    await page.keyboard.press('Space')
    await expect(name).toHaveValue('field take ')
    await expect(page.getByRole('button', { name: 'Pause', exact: true })).toHaveCount(0)
    const submit = exporter.getByRole('button', { name: 'Export', exact: true })
    await submit.focus()
    const download = page.waitForEvent('download', { timeout: 20_000 }).catch(() => null)
    await page.keyboard.press('Enter')
    const file = await download
    if (file) expect(file.suggestedFilename().length).toBeGreaterThan(0)
    else await expect(exporter).toBeVisible()
  })

  test('keeps Keyboard-First for this page and drops it on reload', async ({ page }) => {
    await boot(page)
    await openAccess(page)
    const pref = page.getByRole('switch', { name: 'Keyboard-First' })
    await expect(pref).not.toBeChecked()
    await pref.focus()
    await page.keyboard.press('Space')
    await expect(pref).toBeChecked()
    await expect(page.locator('html')).toHaveAttribute('data-keyboard-first', 'on')
    await pref.focus()
    await page.keyboard.press('Space')
    await expect(pref).not.toBeChecked()
    await page.keyboard.press('Tab')
    const moved = await page.evaluate(() => document.activeElement?.tagName)
    expect(moved).toBeTruthy()
    await page.keyboard.press('Escape')
    await page.reload()
    await page.getByRole('button', { name: 'Settings', exact: true }).waitFor()
    await expect(page.locator('html')).toHaveAttribute('data-keyboard-first', 'off')
  })
})
